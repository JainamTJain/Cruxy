/**
 * Emit supabase/migrations/00015_workstream_e_team_space.sql from buildTeamSpaceSeed.
 * Run: npx tsx scripts/emit-team-seed-sql.ts
 */
import { writeFileSync } from "fs";
import { buildContentSeed } from "../src/lib/seed/build-content";
import { buildTeamSpaceSeed } from "../src/lib/team/seed";
import { caseId, SEED_PERSON_IDS, SEED_TEAM_IDS } from "../src/lib/seed/ids";

function esc(s: string) {
  return s.replace(/'/g, "''");
}
function j(v: unknown) {
  return esc(JSON.stringify(v));
}

function caseNumberFromId(id: string): number {
  return Number(id.slice(-2));
}

async function main() {
  const content = await buildContentSeed(process.cwd());
  const seed = buildTeamSpaceSeed({
    onePagers: content.one_pagers,
    caseRoles: content.case_roles,
  });

  const lines: string[] = [];
  lines.push(
    "-- Workstream E: team board seed (claim maps, chat, Case 10 gap, Case 9 v7)",
  );
  lines.push("-- Idempotent. Reserved migration number 00015.");
  lines.push("-- Generated by scripts/emit-team-seed-sql.ts — re-run to refresh.");
  lines.push("");
  lines.push(
    "-- Case 10 Team 3: leave Lead 1 empty so the board shows a gap",
  );
  lines.push(
    `delete from case_roles where team_id = '${SEED_TEAM_IDS.team3}' and case_id = (select id from cases where number = 10) and role = 'lead_1';`,
  );
  lines.push("");
  lines.push("-- Case 9: Katie made Jainam Lead 1; Daniel takes counter");
  lines.push(
    `delete from case_roles where team_id = '${SEED_TEAM_IDS.team3}' and case_id = (select id from cases where number = 9) and (role in ('lead_1', 'counter_arguer') or person_id = '${SEED_PERSON_IDS.Jainam}');`,
  );
  const case9Roles = seed.case_roles.filter(
    (r) =>
      r.case_id === caseId(9) &&
      (r.role === "lead_1" || r.role === "counter_arguer"),
  );
  lines.push(
    `insert into case_roles (id, team_id, case_id, person_id, role, created_at, created_by) values`,
  );
  lines.push(
    case9Roles
      .map(
        (r) =>
          `  ('${r.id}', '${SEED_TEAM_IDS.team3}', (select id from cases where number = 9), '${r.person_id}', '${r.role}', '${r.created_at}', '${SEED_PERSON_IDS.Katie}')`,
      )
      .join(",\n"),
  );
  lines.push(`on conflict (id) do nothing;`);
  lines.push("");

  lines.push("-- Channels");
  lines.push("insert into chats (id, channel, team_id, created_at) values");
  lines.push(
    seed.chats
      .map(
        (c) =>
          `  ('${c.id}', '${c.channel}', ${c.team_id ? `'${c.team_id}'` : "null"}, '${c.created_at}')`,
      )
      .join(",\n"),
  );
  lines.push("on conflict (channel) do nothing;");
  lines.push("");

  lines.push("-- Claim map versions");
  lines.push(
    "insert into claim_map_versions (id, team_id, case_id, version, body, change_summary, created_by, created_at) values",
  );
  lines.push(
    seed.claim_map_versions
      .map((v) => {
        const num = caseNumberFromId(v.case_id);
        return `  ('${v.id}', '${v.team_id}', (select id from cases where number = ${num}), ${v.version}, '${j(v.body)}'::jsonb, '${esc(v.change_summary)}', '${v.created_by}', '${v.created_at}')`;
      })
      .join(",\n"),
  );
  lines.push("on conflict (team_id, case_id, version) do nothing;");
  lines.push("");

  lines.push("-- Confirmations");
  lines.push(
    "insert into claim_map_confirmations (id, version_id, person_id, confirmed_at) values",
  );
  lines.push(
    seed.claim_map_confirmations
      .map(
        (c) =>
          `  ('${c.id}', '${c.version_id}', '${c.person_id}', '${c.confirmed_at}')`,
      )
      .join(",\n"),
  );
  lines.push("on conflict (version_id, person_id) do nothing;");
  lines.push("");

  lines.push("-- Alignment questions (Jainam on Case 9 v7)");
  lines.push(
    "insert into alignment_questions (id, version_id, person_id, questions, answers, drifted, created_at, answered_at) values",
  );
  lines.push(
    seed.alignment_questions
      .map(
        (a) =>
          `  ('${a.id}', '${a.version_id}', '${a.person_id}', '${j(a.questions)}'::jsonb, null, false, '${a.created_at}', null)`,
      )
      .join(",\n"),
  );
  lines.push("on conflict (id) do nothing;");
  lines.push("");

  const t3chat = seed.chats.find((c) => c.team_id === SEED_TEAM_IDS.team3)!;
  lines.push(
    "-- Team 3 chat messages (resolve chat_id by channel so re-runs stay linked)",
  );
  for (const m of seed.messages) {
    const caseNum = m.case_id ? caseNumberFromId(m.case_id) : null;
    lines.push(
      `insert into messages (id, chat_id, person_id, from_cruxy, body, is_idea, mention_ids, case_id, link_refs, created_at)`,
    );
    lines.push(
      `select '${m.id}', c.id, ${m.person_id ? `'${m.person_id}'` : "null"}, ${m.from_cruxy}, '${esc(m.body)}', ${m.is_idea}, '${j(m.mention_ids)}'::uuid[], ${caseNum != null ? `(select id from cases where number = ${caseNum})` : "null"}, ${m.link_refs ? `'${j(m.link_refs)}'::jsonb` : "null"}, '${m.created_at}'`,
    );
    lines.push(`from chats c where c.channel = '${t3chat.channel}'`);
    lines.push(`and not exists (select 1 from messages where id = '${m.id}');`);
    lines.push("");
  }

  const out = "supabase/migrations/00015_workstream_e_team_space.sql";
  writeFileSync(out, `${lines.join("\n")}\n`);
  console.log("wrote", out);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
