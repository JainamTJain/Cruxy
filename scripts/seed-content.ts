/**
 * Workstream B: parse docs/domain/cases into structured seed SQL + verify idempotency.
 *
 * Usage: npx tsx scripts/seed-content.ts
 * Writes supabase/seed/*.sql (safe to re-run; ON CONFLICT DO UPDATE).
 */
import { createHash } from "crypto";
import { promises as fs } from "fs";
import path from "path";
import { buildContentSeed } from "../src/lib/seed/build-content";
import { emitContentSql } from "../src/lib/seed/emit-sql";
import { assertSeedQuality } from "../src/lib/seed/quality";

const ROOT = path.resolve(__dirname, "..");
const SEED_DIR = path.join(ROOT, "supabase/seed");

async function main() {
  const bundle = await buildContentSeed(ROOT);
  const files = emitContentSql(bundle);

  await fs.mkdir(SEED_DIR, { recursive: true });

  const hashes: string[] = [];
  for (const [name, sql] of Object.entries(files).sort()) {
    const out = path.join(SEED_DIR, name);
    const header = `-- Generated by scripts/seed-content.ts — do not edit by hand.\n-- Re-run: npx tsx scripts/seed-content.ts\n\n`;
    const body = header + sql;
    await fs.writeFile(out, body);
    hashes.push(createHash("sha256").update(body).digest("hex"));
    console.log(
      `wrote ${name} (${body.length} bytes)`,
    );
  }

  // Idempotency check: second build must match first
  const bundle2 = await buildContentSeed(ROOT);
  const files2 = emitContentSql(bundle2);
  for (const name of Object.keys(files).sort()) {
    const a = createHash("sha256").update(files[name]!).digest("hex");
    const b = createHash("sha256").update(files2[name]!).digest("hex");
    if (a !== b) {
      throw new Error(`Non-idempotent SQL for ${name}`);
    }
  }

  const summary = {
    cases: bundle.cases.length,
    active_cases: bundle.cases.filter((c) => c.active).length,
    stakeholders: bundle.stakeholders.length,
    claims: bundle.claims.length,
    supports: bundle.supports.length,
    backings: bundle.backings.length,
    counterclaims: bundle.counterclaims.length,
    truth_items: bundle.truth_items.length,
    questions: bundle.questions.length,
    opposing_positions: bundle.opposing_positions.length,
    one_pagers: bundle.one_pagers.length,
    flashcards: bundle.flashcards.length,
    case_roles: bundle.case_roles.length,
    proposals: bundle.proposals.length,
    scoring_card_items: bundle.scoring_card_items.length,
  };
  console.log(JSON.stringify(summary, null, 2));
  console.log("idempotent: ok");

  // Spot-check Case 10 title and inactive cases
  const c10 = bundle.cases.find((c) => c.number === 10);
  if (c10?.title !== "To Be, or Not to Be…Forgotten?") {
    throw new Error(`Case 10 title wrong: ${c10?.title}`);
  }
  for (const n of [2, 6, 8]) {
    const c = bundle.cases.find((x) => x.number === n);
    if (!c || c.active) throw new Error(`Case ${n} should be inactive`);
  }

  // Parser sanity: every active case has 2 claims with 3 supports
  for (const p of bundle.parsed) {
    const active = bundle.cases.find((c) => c.number === p.number)?.active;
    if (!active) continue;
    if (p.claim1.supports.length < 3 || p.claim2.supports.length < 3) {
      console.warn(
        `warn: Case ${p.number} supports C1=${p.claim1.supports.length} C2=${p.claim2.supports.length}`,
      );
    }
    if (!p.crux || !p.trap) {
      throw new Error(`Case ${p.number} missing crux/trap`);
    }
  }

  const { parsed: _parsed, ...shipped } = bundle;
  assertSeedQuality(shipped);
  console.log("seed quality: ok");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
